#!/usr/bin/env python3
"""Generates src/ckN/states.rs from the state table in the executable.

State records are read from DGROUP of the unpacked executable (EP=4|5|6,
default 6); names of states and of the think/contact/react functions come
from tools/states_kN.py (identified while analysing the decompiled code
with REA). For Keen 4 and 5 the functions of the shared CK_* modules are
found through re/kN/funcs_map.txt (the matching Keen 6 function).
Usage: EP=N python3 -I tools/gen_states.py (run from the repository root)
"""
import struct, sys, os, importlib.util
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'explore.py')).read())
DG = lin(DGLIN, 0xffff)

def rec(o):
    return struct.unpack_from('<8h7H', DG, o)

def fp(o, s):
    return None if (o, s) == (0, 0) else (s + 0x1000) * 16 + o

def load_tables(ep):
    spec = importlib.util.spec_from_file_location('st', os.path.join(_ROOT, 'tools', 'states_k%s.py' % ep))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m

T = load_tables(EP)
STATES = dict(T.STATES)
FUNCS = dict(T.FUNCS)
# per-module additions (tools/states_kN_<module>.py): RENAME {offset: name}
# for the states of that module, FUNCS {address: 'module::fn'}
import glob
EXTRA_FUNCS = {}
for f in sorted(glob.glob(os.path.join(_ROOT, 'tools', 'states_k%s_*.py' % EP))):
    spec = importlib.util.spec_from_file_location('stx', f)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    STATES.update(getattr(m, 'RENAME', {}))
    EXTRA_FUNCS.update(getattr(m, 'FUNCS', {}))
FUNCS.update(EXTRA_FUNCS)
if EP != '6':
    # shared modules: use the Keen 6 name of the matching function
    k6 = load_tables('6').FUNCS
    shared = ('phys::', 'keen::', 'keen2::')
    for l in open(os.path.join(_ROOT, 're', 'k' + EP, 'funcs_map.txt')):
        a, b = (int(x, 16) for x in l.split()[:2])
        if a not in FUNCS and b in k6 and k6[b].startswith(shared):
            FUNCS[a] = k6[b]
    for a in getattr(T, 'NOT_SHARED', ()):
        FUNCS.pop(a, None)
    FUNCS.update(T.FUNCS)
    FUNCS.update(EXTRA_FUNCS)

PROG = ['Step', 'Slide', 'Think', 'StepThink', 'SlideThink']


def main():
    names = list(STATES.values())
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit('duplicate state names: ' + ' '.join(sorted(dup)))
    out = []
    out.append('//! State tables of Keen %s, generated by tools/gen_states.py from the' % EP)
    out.append('//! statetype records in the executable data segment. Do not edit by hand.')
    out.append('')
    out.append('#![allow(clippy::all)]')
    out.append('use super::defs::{Progress, State};')
    out.append('use super::*;')
    out.append('')
    missing = set()
    for off in sorted(STATES):
        name = STATES[off]
        l, r, prog, skip, push, tic, xm, ym, t0, t1, c0, c1, r0, r1, nx = rec(off)
        def fn(o, s):
            a = fp(o, s)
            if a is None:
                return 'None'
            if a not in FUNCS:
                missing.add(a)
                return 'None /* %05x */' % a
            return 'Some(%s)' % FUNCS[a]
        nxt = 'None' if nx == 0 else ('Some(&%s)' % STATES[nx] if nx in STATES else None)
        if nxt is None:
            print('state %04x: unknown next %04x' % (off, nx), file=sys.stderr)
            nxt = 'None'
        out.append('/// 0x%04x' % off)
        out.append('pub static %s: State = State {' % name)
        out.append('    name: "%s",' % name.lower())
        out.append('    left: %d,' % l)
        out.append('    right: %d,' % r)
        out.append('    progress: Progress::%s,' % PROG[prog])
        out.append('    skippable: %s,' % ('true' if skip else 'false'))
        out.append('    pushtofloor: %s,' % ('true' if push else 'false'))
        out.append('    tictime: %d,' % tic)
        out.append('    xmove: %d,' % xm)
        out.append('    ymove: %d,' % ym)
        out.append('    think: %s,' % fn(t0, t1))
        out.append('    contact: %s,' % fn(c0, c1))
        out.append('    react: %s,' % fn(r0, r1))
        out.append('    next: %s,' % nxt)
        out.append('};')
        out.append('')
    out.append('/// All states, for save games (index <-> state).')
    out.append('pub static ALL_STATES: &[&State] = &[')
    for off in sorted(STATES):
        out.append('    &%s,' % STATES[off])
    out.append('];')
    out.append('')
    out.append('/// Finds a state by the DGROUP offset it had in the original executable.')
    out.append('pub fn state_by_offset(off: u16) -> Option<&\'static State> {')
    out.append('    match off {')
    for off in sorted(STATES):
        out.append('        0x%04x => Some(&%s),' % (off, STATES[off]))
    out.append('        _ => None,')
    out.append('    }')
    out.append('}')
    open(os.path.join(_ROOT, 'src', 'ck' + EP, 'states.rs'), 'w').write('\n'.join(out) + '\n')
    if missing:
        print('missing functions:', ' '.join('%05x' % m for m in sorted(missing)), file=sys.stderr)


main()
